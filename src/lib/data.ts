// ---------------------------------------------------------------------------
// Curation overlay (data/curation.json) — see NAMING.md §実施口径 and the
// _meta block inside curation.json for the full rules. The export file and
// its contract are never edited; this layer is applied in memory at build:
//
//   keep        — rename (canonicalNameEn / canonicalNameJaClean / newSlug)
//   merge_into  — fold this model's sales into the target model and drop
//                 this page. Fold rules: volumes sum; price ranges take
//                 min/max; medians / trend / sell-hours are volume-weighted
//                 averages of the source values (weights: soldVolume90d for
//                 medians, soldVolume30d for trend), rounded to the nearest
//                 yen; the overall USD median is recomputed from the merged
//                 JPY median at the export exchange rate; by-condition
//                 grades merge per grade; time series merge per date with
//                 volume-weighted medians; the source's cleaned Japanese
//                 name joins the target's aliases.
//   exclude_lot — bundle/lot or non-product entry: no page, no listing.
//   hold        — identity cannot be supported: keep current behaviour.
//
// Old URLs of renamed/merged models get static redirect pages under
// public/ (generated by scripts/generate-redirects.mjs). Watchlist entries
// stored under old slugs are migrated by getWatchlistMigration() below.
// ---------------------------------------------------------------------------

export interface CurationEntry {
  action: 'keep' | 'merge_into' | 'exclude_lot' | 'hold';
  canonicalNameEn?: string | null;
  canonicalNameJaClean?: string | null;
  newSlug?: string | null;
  mergeInto?: string;
  reason?: string;
}

export type CurationMap = Record<string, CurationEntry>;

let cachedCuration: CurationMap | null = null;

export function getCuration(): CurationMap {
  if (cachedCuration) return cachedCuration;
  const useFixtures = process.env.LOAD_FIXTURES === 'true' || import.meta.env.LOAD_FIXTURES === 'true';
  if (useFixtures) {
    cachedCuration = {};
    return cachedCuration;
  }
  try {
    const raw = fs.readFileSync(path.resolve(process.cwd(), 'data/curation.json'), 'utf-8');
    const parsed = JSON.parse(raw) as Record<string, unknown>;
    const map: CurationMap = {};
    for (const [key, value] of Object.entries(parsed)) {
      if (key.startsWith('_')) continue;
      map[key] = value as CurationEntry;
    }
    cachedCuration = map;
    return cachedCuration;
  } catch (err) {
    console.warn('[data] Could not read data/curation.json, serving export uncurated:', err);
    cachedCuration = {};
    return cachedCuration;
  }
}

function franchisePathOf(model: ModelData): string {
  return model.franchise.replace('_', '-');
}

function weightedAvg(pairs: Array<{ value: number; weight: number }>): number {
  let totalWeight = 0;
  let total = 0;
  for (const p of pairs) {
    if (!isFinite(p.value)) continue;
    const w = p.weight > 0 ? p.weight : 0;
    total += p.value * w;
    totalWeight += w;
  }
  if (totalWeight === 0) {
    const values = pairs.map(p => p.value).filter(v => isFinite(v));
    if (!values.length) return 0;
    return values.reduce((a, b) => a + b, 0) / values.length;
  }
  return total / totalWeight;
}

function mergeCondition(target: ConditionMetric, source: ConditionMetric): ConditionMetric {
  const tw = target.soldVolume30d || 0;
  const sw = source.soldVolume30d || 0;
  const medians: Array<{ value: number; weight: number }> = [];
  if (target.medianPriceJpy !== null && target.medianPriceJpy !== undefined) {
    medians.push({ value: target.medianPriceJpy, weight: tw });
  }
  if (source.medianPriceJpy !== null && source.medianPriceJpy !== undefined) {
    medians.push({ value: source.medianPriceJpy, weight: sw });
  }
  const medianJpy = medians.length ? Math.round(weightedAvg(medians)) : null;
  const mins = [target.priceMinJpy, source.priceMinJpy].filter(
    (v): v is number => typeof v === 'number' && v > 0
  );
  const maxs = [target.priceMaxJpy, source.priceMaxJpy].filter(
    (v): v is number => typeof v === 'number' && v > 0
  );
  return {
    ...target,
    medianPriceJpy: medianJpy,
    medianPriceUsd:
      medianJpy !== null && target.medianPriceUsd !== null && source.medianPriceUsd !== null
        ? Math.round(
            weightedAvg([
              { value: target.medianPriceUsd ?? 0, weight: tw },
              { value: source.medianPriceUsd ?? 0, weight: sw }
            ]) * 100
          ) / 100
        : target.medianPriceUsd ?? source.medianPriceUsd ?? null,
    priceMinJpy: mins.length ? Math.min(...mins) : target.priceMinJpy,
    priceMaxJpy: maxs.length ? Math.max(...maxs) : target.priceMaxJpy,
    soldVolume30d: tw + sw,
    note: target.note ?? source.note
  };
}

function mergeTimeSeries(
  target: TimeSeriesPoint[],
  source: TimeSeriesPoint[]
): TimeSeriesPoint[] {
  const byDate = new Map<string, TimeSeriesPoint[]>();
  for (const point of [...target, ...source]) {
    const list = byDate.get(point.date) ?? [];
    list.push(point);
    byDate.set(point.date, list);
  }
  const grades = ['sealed', 'cib', 'loose'] as const;
  const merged: TimeSeriesPoint[] = [];
  for (const [date, points] of byDate) {
    const byGrade: TimeSeriesPoint['byGrade'] = {};
    for (const grade of grades) {
      const vals = points
        .filter(p => p.byGrade && p.byGrade[grade] !== null && p.byGrade[grade] !== undefined)
        .map(p => ({ value: p.byGrade![grade] as number, weight: p.volume || 0 }));
      byGrade[grade] = vals.length ? Math.round(weightedAvg(vals)) : null;
    }
    merged.push({
      date,
      medianJpy: Math.round(
        weightedAvg(points.map(p => ({ value: p.medianJpy, weight: p.volume || 0 })))
      ),
      volume: points.reduce((sum, p) => sum + (p.volume || 0), 0),
      byGrade
    });
  }
  return merged.sort((a, b) => a.date.localeCompare(b.date));
}

/** Fold `source`'s sales into `target` in place. See overlay rules above. */
function foldInto(target: ModelData, source: ModelData, exchangeRateUsdJpy: number): void {
  const t = target.metrics.overall;
  const s = source.metrics.overall;
  const w90t = t.soldVolume90d || 0;
  const w90s = s.soldVolume90d || 0;
  const w30t = t.soldVolume30d || 0;
  const w30s = s.soldVolume30d || 0;

  const mergedMedianJpy = Math.round(
    weightedAvg([
      { value: t.medianPriceJpy, weight: w90t },
      { value: s.medianPriceJpy, weight: w90s }
    ])
  );

  target.metrics.overall = {
    medianPriceJpy: mergedMedianJpy,
    medianPriceUsd:
      exchangeRateUsdJpy > 0
        ? Math.round((mergedMedianJpy / exchangeRateUsdJpy) * 100) / 100
        : t.medianPriceUsd,
    priceRangeMinJpy: Math.min(
      ...[t.priceRangeMinJpy, s.priceRangeMinJpy].filter(v => v > 0)
    ),
    priceRangeMaxJpy: Math.max(t.priceRangeMaxJpy, s.priceRangeMaxJpy),
    soldVolume30d: w30t + w30s,
    soldVolume90d: w90t + w90s,
    priceTrendPct30d:
      Math.round(
        weightedAvg([
          { value: t.priceTrendPct30d, weight: w30t },
          { value: s.priceTrendPct30d, weight: w30s }
        ]) * 10
      ) / 10,
    averageSellHours:
      Math.round(
        weightedAvg([
          { value: t.averageSellHours, weight: w90t },
          { value: s.averageSellHours, weight: w90s }
        ]) * 10
      ) / 10
  };

  const grades = ['new_sealed', 'like_new', 'used', 'damaged_or_junk'] as const;
  for (const grade of grades) {
    target.metrics.byCondition[grade] = mergeCondition(
      target.metrics.byCondition[grade],
      source.metrics.byCondition[grade]
    );
  }

  // Only the domestic C2C median is real data; it follows the merged overall
  // median. The other spread fields stay as exported (zeros are not rendered
  // as values — see ProcurementBox).
  target.metrics.marketSpread = {
    ...target.metrics.marketSpread,
    japanDomesticC2cMedianJpy: mergedMedianJpy
  };

  target.timeSeries = {
    days30: mergeTimeSeries(target.timeSeries.days30, source.timeSeries.days30),
    days90: mergeTimeSeries(target.timeSeries.days90, source.timeSeries.days90),
    year1: mergeTimeSeries(target.timeSeries.year1, source.timeSeries.year1),
    all: mergeTimeSeries(target.timeSeries.all, source.timeSeries.all)
  };

  const sourceNames = [source.canonicalNameJa, source.canonicalNameEn].filter(Boolean);
  target.aliases = Array.from(new Set([...(target.aliases ?? []), ...sourceNames]));
}

export function applyCuration(data: ExportData): ExportData {
  const curation = getCuration();
  if (!Object.keys(curation).length) return data;

  const byOriginalSlug = new Map<string, ModelData>();
  for (const model of data.models) byOriginalSlug.set(model.slug, model);

  const kept: ModelData[] = [];
  const mergeSources: Array<{ source: ModelData; targetSlug: string }> = [];

  for (const model of data.models) {
    const entry = curation[model.slug];
    if (!entry || entry.action === 'hold') {
      kept.push(model);
      continue;
    }
    if (entry.action === 'exclude_lot') continue;
    if (entry.action === 'merge_into') {
      if (entry.mergeInto) mergeSources.push({ source: model, targetSlug: entry.mergeInto });
      continue;
    }
    // keep (+ optional rename)
    if (entry.canonicalNameEn) model.canonicalNameEn = entry.canonicalNameEn;
    if (entry.canonicalNameJaClean) model.canonicalNameJa = entry.canonicalNameJaClean;
    if (entry.newSlug && entry.newSlug !== model.slug) {
      model.slug = entry.newSlug;
      model.canonicalSlug = `${franchisePathOf(model)}/${model.series}/${model.slug}`;
    }
    kept.push(model);
  }

  const keptByOriginalSlug = new Map<string, ModelData>();
  for (const model of kept) {
    // A kept model answers to its original slug via byOriginalSlug identity:
    // find the original key whose object this is.
    for (const [origSlug, orig] of byOriginalSlug) {
      if (orig === model) keptByOriginalSlug.set(origSlug, model);
    }
  }

  for (const { source, targetSlug } of mergeSources) {
    const target = keptByOriginalSlug.get(targetSlug);
    if (!target) {
      console.warn(`[data] curation merge target ${targetSlug} not kept; source ${source.slug} dropped`);
      continue;
    }
    const entry = curation[source.slug];
    if (entry?.canonicalNameJaClean) source.canonicalNameJa = entry.canonicalNameJaClean;
    foldInto(target, source, data.exchangeRateUsdJpy);
  }

  return { ...data, models: kept };
}

export interface SlugRedirect {
  fromSlug: string;
  fromCanonical: string;
  toSlug: string;
  toCanonical: string;
}

/** Old → new slug redirects for every renamed or merged model. */
export function getSlugRedirects(): SlugRedirect[] {
  const curation = getCuration();
  const raw = getRawExportData();
  const redirects: SlugRedirect[] = [];
  const finalSlugOf = (originalSlug: string): { slug: string; canonical: string } | null => {
    const model = raw.models.find(m => m.slug === originalSlug);
    if (!model) return null;
    const entry = curation[originalSlug];
    const slug = entry?.action === 'keep' && entry.newSlug ? entry.newSlug : originalSlug;
    return {
      slug,
      canonical: `${franchisePathOf(model)}/${model.series}/${slug}`
    };
  };

  for (const model of raw.models) {
    const entry = curation[model.slug];
    if (!entry) continue;
    const fromCanonical = `${franchisePathOf(model)}/${model.series}/${model.slug}`;
    if (entry.action === 'keep' && entry.newSlug && entry.newSlug !== model.slug) {
      const to = finalSlugOf(model.slug);
      if (to) redirects.push({ fromSlug: model.slug, fromCanonical, toSlug: to.slug, toCanonical: to.canonical });
    } else if (entry.action === 'merge_into' && entry.mergeInto) {
      const to = finalSlugOf(entry.mergeInto);
      if (to) redirects.push({ fromSlug: model.slug, fromCanonical, toSlug: to.slug, toCanonical: to.canonical });
    }
  }
  return redirects;
}

export interface WatchlistMigration {
  /** old slug -> replacement entry details (renamed or merged models) */
  renames: Record<
    string,
    { slug: string; name: string; ja: string; franchise: string; series: string }
  >;
  /** old slugs whose model no longer exists (exclude_lot) */
  removed: string[];
}

/**
 * Migration map for browser-stored watchlist entries keyed by slug.
 * The inline script in Layout.astro rewrites localStorage entries through
 * this map on every page load: renamed/merged slugs point at the surviving
 * model, excluded slugs are dropped (their page no longer exists), and any
 * duplicate created by a merge is de-duplicated.
 */
export function getWatchlistMigration(): WatchlistMigration {
  const curation = getCuration();
  const models = getAllModels();
  const bySlug = new Map(models.map(m => [m.slug, m]));
  const renames: WatchlistMigration['renames'] = {};
  const removed: string[] = [];

  for (const redirect of getSlugRedirects()) {
    const target = bySlug.get(redirect.toSlug);
    if (!target) continue;
    renames[redirect.fromSlug] = {
      slug: target.slug,
      name: target.canonicalNameEn,
      ja: target.canonicalNameJa,
      franchise: franchisePathOf(target),
      series: target.series
    };
  }
  for (const [slug, entry] of Object.entries(curation)) {
    if (entry.action === 'exclude_lot') removed.push(slug);
  }
  return { renames, removed };
}

let cachedData: ExportData | null = null;
let cachedRawData: ExportData | null = null;

function emptyExportData(): ExportData {
  return {
    version: '1.0.0',
    pipelineStatus: 'compiling',
    pipelineMessage: 'Price index pipeline is compiling verified Tokyo sold data.',
    lastExportAt: new Date().toISOString(),
    exchangeRateUsdJpy: 149.8,
    exchangeRateDate: '2026-10-25',
    platformsTracked: ['Mercari Japan', 'Yahoo! Auctions Japan', 'Rakuma', 'Mandarake', 'Suruga-ya'],
    models: []
  };
}

function readExportData(): ExportData {
  const useFixtures = process.env.LOAD_FIXTURES === 'true' || import.meta.env.LOAD_FIXTURES === 'true';
  const dataFile = useFixtures
    ? path.resolve(process.cwd(), 'tests/fixtures/export-fixtures.json')
    : path.resolve(process.cwd(), 'data/export.json');

  try {
    const raw = fs.readFileSync(dataFile, 'utf-8');
    return JSON.parse(raw) as ExportData;
  } catch (err) {
    console.warn(`[data] Could not read ${dataFile}, returning empty schema:`, err);
    return emptyExportData();
  }
}

export function getRawExportData(): ExportData {
  if (cachedRawData) return cachedRawData;
  cachedRawData = readExportData();
  return cachedRawData;
}

export function getExportData(): ExportData {
  if (cachedData) return cachedData;
  // Deep-clone the raw export so the curation overlay never mutates it:
  // getSlugRedirects()/getWatchlistMigration() rely on original slugs.
  const raw = JSON.parse(JSON.stringify(getRawExportData())) as ExportData;
  cachedData = applyCuration(raw);
  return cachedData;
}

export function getAllModels(): ModelData[] {
  return getExportData().models;
}

export function getModelsByFranchise(franchiseKey: string): ModelData[] {
  const norm = franchiseKey.replace('-', '_');
  return getAllModels().filter(m => m.franchise === norm);
}

export function getModelByCanonical(franchiseKey: string, seriesKey: string, slugKey: string): ModelData | undefined {
  const normFranchise = franchiseKey.replace('-', '_');
  return getAllModels().find(
    m => m.franchise === normFranchise && m.series === seriesKey && m.slug === slugKey
  );
}

// Design.md §3.3 Numeric Formatting Rules:
// "No Hand-Rolled Currency Formats: All currency figures must render through
//  Intl.NumberFormat('ja-JP', { style: 'currency', currency: 'JPY', maximumFractionDigits: 0 })
//  and Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 2 })."
const jpyFormatter = new Intl.NumberFormat('ja-JP', {
  style: 'currency',
  currency: 'JPY',
  maximumFractionDigits: 0
});

const usdFormatter = new Intl.NumberFormat('en-US', {
  style: 'currency',
  currency: 'USD',
  minimumFractionDigits: 2,
  maximumFractionDigits: 2
});

export function formatJpy(amount: number | null | undefined): string {
  if (amount === null || amount === undefined || isNaN(amount)) return '—';
  return jpyFormatter.format(amount);
}

export function formatUsd(amount: number | null | undefined): string {
  if (amount === null || amount === undefined || isNaN(amount)) return '—';
  return usdFormatter.format(amount);
}

export function formatTrend(pct: number | null | undefined): { text: string; isPositive: boolean; isNegative: boolean } {
  if (pct === null || pct === undefined || isNaN(pct)) {
    return { text: '0.0%', isPositive: false, isNegative: false };
  }
  const sign = pct > 0 ? '+' : '';
  return {
    text: `${sign}${pct.toFixed(1)}%`,
    isPositive: pct > 0,
    isNegative: pct < 0
  };
}
